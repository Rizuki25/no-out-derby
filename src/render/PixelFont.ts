export function measurePixelText(text: string, scale = 1): number {
  if (!text.length) return 0;
  return text.length * 6 * scale - scale;
}

export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  align: 'left' | 'center' | 'right' = 'left',
  shadowColor?: string
): void {
  const upper = text.toUpperCase();
  const totalW = measurePixelText(upper, scale);
  let startX = Math.round(x);
  if (align === 'center') startX = Math.round(x - totalW * 0.5);
  else if (align === 'right') startX = Math.round(x - totalW);
  const startY = Math.round(y);

  const renderPass = (ox: number, oy: number, fill: string) => {
    ctx.fillStyle = fill;
    let cx = startX + ox;
    for (let i = 0; i < upper.length; i++) {
      const ch = upper[i];
      const rows = GLYPHS_5X7[ch] ?? GLYPHS_5X7[' '];
      for (let r = 0; r < 7; r++) {
        const mask = rows[r];
        if (!mask) continue;
        for (let c = 0; c < 5; c++) {
          if (mask & (1 << (4 - c))) {
            ctx.fillRect(cx + c * scale, startY + oy + r * scale, scale, scale);
          }
        }
      }
      cx += 6 * scale;
    }
  };

  if (shadowColor) {
    renderPass(scale, scale, shadowColor);
  }
  renderPass(0, 0, color);
}
